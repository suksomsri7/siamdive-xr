        [Test]
        public void ShoalsStayShoals()
        {
            // A pod of orcas is SCHOOL-kind AND an animal; the prefix has to win, or the map
            // grows eleven separate orca brains instead of one pod.
            foreach (string id in new[] { "school:scad", "school:barracuda", "pod:orca",
                                          "pod:humpback", "pod:hammerhead" })
            {
                Assert.AreEqual(MarineRoute.School, MarineRouting.For(id, "SCHOOL"), id);
                Assert.IsFalse(MarineRouting.IsSolo(id, "SCHOOL"), id);
            }
        }

        [Test]
        public void WarpGatesAreNeverAnimals()
        {
            // A gate is built from primitives and is in no manifest, so it can arrive with any
            // kind at all — including, if a caller is careless, an animal's.
            Assert.AreEqual(MarineRoute.None, MarineRouting.For("warp:0", "MARINE_LIFE"));
            Assert.AreEqual(MarineRoute.None, MarineRouting.For("warp:1", null));
        }

        [Test]
        public void UnknownKindsAndNullsAreInert()
        {
            Assert.AreEqual(MarineRoute.None, MarineRouting.For("losin:octopus", null));
            Assert.AreEqual(MarineRoute.None, MarineRouting.For("losin:octopus", "GRAVEL"));
            Assert.AreEqual(MarineRoute.None, MarineRouting.For(null, null));
            Assert.AreEqual(MarineRoute.None, MarineRouting.For("", ""));
            Assert.IsFalse(MarineRouting.IsAnimalKind(null));
        }

        [Test]
        public void KindMatchingIsCaseInsensitive()
        {
            Assert.AreEqual(MarineRoute.Solo, MarineRouting.For("losin:octopus", "marine_life"));
            Assert.AreEqual(MarineRoute.School, MarineRouting.For("POD:ORCA", "school"));
        }

