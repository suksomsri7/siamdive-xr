        [Test]
        public void TheHuntBudgetCutsOffWhereItSays()
        {
            Assert.IsTrue(MarineRouting.MayHunt(0));
            Assert.IsTrue(MarineRouting.MayHunt(MarineRouting.SoloHuntBudget - 1));
            Assert.IsFalse(MarineRouting.MayHunt(MarineRouting.SoloHuntBudget));
            Assert.IsFalse(MarineRouting.MayHunt(500));
            Assert.IsFalse(MarineRouting.MayHunt(-1));
            // The scan is O(n²) per tick: 40² = 1,600 tests every 0.7 s is free, and the next
            // order of magnitude is not. If this number grows, re-measure on a phone first.
            Assert.LessOrEqual(MarineRouting.SoloHuntBudget, 64);
        }

        // ── per-placement seeding ────────────────────────────────────────────────

        [Test]
        public void FiveSharksOnOneMapAreFiveDifferentSharks()
        {
            // 🔴 The Posidon case: an author drops the same shark five times. Seeded from a
            // counter they would be identical; seeded from the clock they would be different
            // every time the map was opened and no screenshot would ever reproduce.
            var seen = new HashSet<uint>();
            for (int i = 0; i < 5; i++)
                seen.Add(MarineRouting.PlacementSeed("losin:hammerhead_shark", i * 37.5, 60.0, i * -21.25));
            Assert.AreEqual(5, seen.Count);
        }

        [Test]
        public void TheSameMapReopensTheSame()
        {
            Assert.AreEqual(MarineRouting.PlacementSeed("mdl:seal", 12.3, 40.0, -8.75),
                            MarineRouting.PlacementSeed("mdl:seal", 12.3, 40.0, -8.75));
            // Quantised to a tenth of a unit, so the sub-millimetre wobble a float round-trip
            // through the save file introduces cannot reseed an animal nobody moved.
            //
            // ⚠️ A quantisation has boundaries and this one is no exception: a coordinate sitting
            // exactly on a .x5 can still flip (−8.75 rounds to −88, −8.7499 to −87). That is
            // acceptable — it takes an author placing an animal on precisely that line AND the
            // file round-tripping across it, and the cost is one animal drawing a different
            // personality. The alternative, no quantisation at all, means EVERY animal rerolls on
            // every save.
            Assert.AreEqual(MarineRouting.PlacementSeed("mdl:seal", 12.30, 40.0, -8.72),
                            MarineRouting.PlacementSeed("mdl:seal", 12.3001, 40.0, -8.7201));
        }

        [Test]
        public void DifferentSpeciesInTheSameSpotDiffer()
        {
            Assert.AreNotEqual(MarineRouting.PlacementSeed("mdl:seal", 5.0, 5.0, 5.0),
                               MarineRouting.PlacementSeed("mdl:penguin", 5.0, 5.0, 5.0));
        }

        [Test]
        public void ASeedIsNeverZero()
        {
            // 0 is a legitimate hash output and a terrible seed: FishMind.Rand01 folds it with
            // the tick, and a whole species sharing seed 0 would share every decision.
            Assert.AreNotEqual(0u, MarineRouting.PlacementSeed("", 0, 0, 0));
            Assert.AreNotEqual(0u, MarineRouting.PlacementSeed(null, 0, 0, 0));
        }

        // ── the list itself ──────────────────────────────────────────────────────

        [Test]
        public void ListMatchesTheShippedManifest()
        {
            string path = ManifestPath();
            if (path == null || !File.Exists(path))
                Assert.Ignore("asset_manifest.json not reachable from here (player build).");

            var fromFile = new List<string>();
            string pending = null;
            foreach (string line in File.ReadAllLines(path))
            {
                string id = Between(line, "\"id\": \"", "\"");
                if (id != null) { pending = id; continue; }
                string kind = Between(line, "\"kind\": \"", "\"");
                if (kind == null) continue;
                if (pending != null) fromFile.Add(pending + "|" + kind);
                pending = null;
            }

            Assert.Greater(fromFile.Count, 0, "could not parse " + path);
            CollectionAssert.AreEquivalent(Modules, fromFile,
                "the manifest changed — regenerate MarineRoutingTests.Modules");
        }

        private static string ManifestPath([CallerFilePath] string here = "")
        {
            DirectoryInfo d = new FileInfo(here).Directory;          // EditMode
            for (int i = 0; i < 3 && d != null; i++) d = d.Parent;   // Tests → Assets → DiveMap
            return d == null ? null : Path.Combine(d.FullName, "Assets", "StreamingAssets", "asset_manifest.json");
        }

        private static string Between(string s, string a, string b)
        {
            int i = s.IndexOf(a, StringComparison.Ordinal);
            if (i < 0) return null;
            i += a.Length;
            int j = s.IndexOf(b, i, StringComparison.Ordinal);
            return j < 0 ? null : s.Substring(i, j - i);
        }
