        private static void Split(string row, out string id, out string kind)
        {
            int bar = row.IndexOf('|');
            id = row.Substring(0, bar);
            kind = row.Substring(bar + 1);
        }

        // ── exhaustive over the manifest ─────────────────────────────────────────

        [Test]
        public void EveryModuleRoutesToExactlyTheRightSystem()
        {
            var wrong = new List<string>();
            foreach (string row in Modules)
            {
                Split(row, out string id, out string kind);

                bool isSchoolId = id.StartsWith("school:", StringComparison.OrdinalIgnoreCase)
                               || id.StartsWith("pod:", StringComparison.OrdinalIgnoreCase);
                bool isAnimal = kind == "MARINE_LIFE" || kind == "SCHOOL"
                             || kind == "FISH" || kind == "TURTLE";

                MarineRoute want = isSchoolId ? MarineRoute.School
                                 : !isAnimal  ? MarineRoute.None
                                 : kind == "SCHOOL" ? MarineRoute.School
                                 : MarineRoute.Solo;

                MarineRoute got = MarineRouting.For(id, kind);
                if (got != want) wrong.Add($"{id} ({kind}): want {want}, got {got}");
            }
            Assert.IsEmpty(wrong, string.Join("\n", wrong));
        }

        [Test]
        public void TheCountsAreWhatTheReefShouldContain()
        {
            int solo = 0, school = 0, none = 0;
            foreach (string row in Modules)
            {
                Split(row, out string id, out string kind);
                switch (MarineRouting.For(id, kind))
                {
                    case MarineRoute.Solo:   solo++;   break;
                    case MarineRoute.School: school++; break;
                    default:                 none++;   break;
                }
            }
            // 🔴 88 is the number this whole phase is about. Before it, THIRTY of those were
            // driven (the msh:* heroes) and the other fifty-eight were furniture.
            Assert.AreEqual(88, solo, "solo animals");
            Assert.AreEqual(11, school, "shoals and pods");
            Assert.AreEqual(176, none, "scenery — coral, rock, wreck, boat, artificial, special");
            Assert.AreEqual(275, Modules.Length);
        }

        [Test]
        public void NoSceneryEverGetsABrain()
        {
            foreach (string row in Modules)
            {
                Split(row, out string id, out string kind);
                if (kind == "MARINE_LIFE" || kind == "SCHOOL" || kind == "FISH" || kind == "TURTLE")
                    continue;
                Assert.AreEqual(MarineRoute.None, MarineRouting.For(id, kind),
                                $"{id} is {kind} and must stay furniture");
                Assert.IsFalse(MarineRouting.IsSolo(id, kind), id);
            }
        }

        [Test]
        public void EveryAnimalGetsOneOrTheOther()
        {
            foreach (string id in SpeciesCoverageTests.Animals)
            {
                // Kind is not needed for the shoals (the prefix decides), and for the rest the
                // coverage list is animals-only by construction — so anything that comes back
                // None here is an animal that would be loaded as scenery.
                string kind = MarineRouting.IsSchoolId(id) ? "SCHOOL" : "MARINE_LIFE";
                Assert.AreNotEqual(MarineRoute.None, MarineRouting.For(id, kind), id);
            }
        }

