namespace DiveMap.Core
{
    /// <summary>
    /// ระยะที่ปุ่มลอยต้องเว้นจากขอบบนของจอ — เป็นตัวเลขล้วน ทดสอบได้โดยไม่ต้องมีจอ.
    ///
    /// ทำไมต้องมี: ในแอปรวม เราตั้งพื้นที่ปลอดภัยของ Unity เป็น **เต็มจอ** โดยตั้งใจ
    /// (ดูเหตุผลยาวใน <c>UiShell.ApplySafeArea</c> — ค่า <c>Screen.safeArea</c> ในโหมดฝังตัว
    /// ไม่ตรงกับสิ่งที่ Unity วาดอยู่ และทำให้ปุ่มขยับเองเมื่อเข้าแมพที่สอง) ผลข้างเคียงคือ
    /// ขอบบนของ Unity = ขอบกระจกจริง ⇒ ปุ่มที่ห่างขอบ 12 px ไปนั่งทับนาฬิกา/แบตเตอรี่
    ///
    /// 🔴 บทเรียนจากโหมด AR (user 16 ส.ค. 2026: "ปุ่ม x อยู่สูงไปคลิกไม่ได้"): บนจอ iPhone
    /// แนวตั้ง แถบสถานะสูงราว 44–54 pt และมุมบนขวายังเป็นโซนที่ระบบกินสัมผัสไปเปิดศูนย์ควบคุม
    /// ⇒ ปุ่มตรงนั้น "ดูเหมือนกดได้ แต่กดไม่ติด" ซึ่งอ่านออกจากภาพถ่ายไม่ได้เลยถ้าไม่รู้ที่มา
    ///
    /// แนวนอนเว้นน้อยกว่ามาก เพราะแถบสถานะของ iOS แนวนอนบนเครื่องมีรอยบากถูกยุบจนเกือบไม่มี
    /// และการเว้น 44 ที่นั่นจะดันปุ่มลงมากลางจอโดยไม่มีเหตุผล
    /// </summary>
    public static class ChromeInset
    {
        /// <summary>แถบสถานะแนวตั้ง (css px) — เผื่อรุ่นที่สูงสุดไว้ก่อน ปุ่มต่ำไปหนึ่งนิ้วยังกดได้ แต่ปุ่มที่สูงไปกดไม่ได้เลย</summary>
        public const float PortraitStatusBar = 44f;

        /// <summary>แนวนอน: แค่ไม่ให้ชนขอบโค้ง</summary>
        public const float LandscapeStatusBar = 6f;

        /// <summary>
        /// ต้องเว้นเท่าไร (css px) สำหรับปุ่มที่เกาะขอบบน.
        /// <paramref name="embeddedInHost"/> = เป็นจอในแอปอื่นไหม — บิลด์เดี่ยวคืน 0 เสมอ
        /// เพราะที่นั่น <c>Screen.safeArea</c> เชื่อถือได้และหักให้แล้ว การเว้นซ้ำ = เว้นสองเท่า
        /// </summary>
        public static float Top(bool embeddedInHost, bool portrait)
        {
            if (!embeddedInHost) return 0f;
            return portrait ? PortraitStatusBar : LandscapeStatusBar;
        }
    }
}
