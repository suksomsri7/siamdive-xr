namespace DiveMap.Core
{
    /// <summary>
    /// ใครแก้แมพได้ หลังการเปลี่ยนทิศ 14 ส.ค. 2026 (WO-PIVOT).
    ///
    /// ทิศใหม่: **การสร้าง/แก้แมพเกิดบนเว็บเท่านั้น** (แอดมินที่ maps.siamdive.com) ส่วน Unity
    /// เป็นจอสำหรับ ดู / AR / ทัวร์. เหตุผลไม่ใช่เรื่องสิทธิ์ แต่เป็นเรื่องต้นทุน: เครื่องมือแก้ไข
    /// ทั้งชุด (ลูกศรสามแกน · undo · ตะกร้า · ปั้นพื้น · เชือก · หมุด) คือของที่เว็บมีครบและดีอยู่
    /// แล้ว การมีสองชุดแปลว่าทุกการแก้ต้องทำสองที่ และฝั่ง Unity แต่ละรอบมีราคา ~110 นาที
    ///
    /// 🔴 ตัดสินจาก <c>NativeBridge.EmbeddedInHost</c> (ข้อเท็จจริงของการแพ็กเกจ จริงตั้งแต่
    /// คำสั่งแรกที่รัน) ไม่ใช่ <c>NativeBoot.LibraryMode</c> (มาจากข้อความของเจ้าบ้าน ซึ่งมาช้าได้
    /// และเคยหายมาแล้ว) — ถ้าใช้ตัวหลัง หน้าต่างช่วงต้นของแต่ละแมพจะยังแก้ได้ชั่วครู่ ซึ่งแย่กว่า
    /// ทั้งสองทางเลือก: ผู้ใช้แตะโดนแล้วแมพเปลี่ยนโดยไม่มีใครตั้งใจ
    ///
    /// บิลด์เดี่ยว (DiveMap บน TestFlight) ไม่เปลี่ยนอะไรเลย — ยังแก้ได้ครบ เพราะเป็นเครื่องมือ QC
    /// ที่ทุก harness ของ CI ใช้อยู่ และการถอดออกจะทำให้ด่านตรวจภาพทั้งชุดตายพร้อมกัน
    /// </summary>
    public static class EditAccess
    {
        /// <summary>
        /// แก้แมพนี้ได้ไหม เมื่อรวมคำตัดสินของเซิร์ฟเวอร์กับที่ที่แอปกำลังรันอยู่.
        /// <paramref name="serverCanEdit"/> = <c>canEdit</c> จาก API ซึ่งยังเป็นความจริงเดียว
        /// เรื่องสิทธิ์ — ตัวนี้แค่ "ปิดเพิ่ม" ไม่เคยเปิดให้ใครที่เซิร์ฟเวอร์ไม่อนุญาต
        /// </summary>
        public static bool MapEditingAllowed(bool serverCanEdit, bool embeddedInHost)
            => serverCanEdit && !embeddedInHost;

        /// <summary>
        /// ปุ่มเครื่องมือแก้ไขควรถูกสร้างขึ้นมาบนจอไหม.
        ///
        /// แยกจาก <see cref="MapEditingAllowed"/> เพราะปุ่มพวกนั้นด่านที่ *เวลากด* (กดแล้วขึ้น
        /// "แมพนี้แก้ไม่ได้") ซึ่งถูกต้องสำหรับแมพของคนอื่นในบิลด์เดี่ยว แต่ผิดสำหรับแอปรวม:
        /// ที่นั่นไม่มีวันแก้ได้เลย ปุ่มที่กดไม่ได้หกปุ่มจึงเป็นแค่ขยะบนจอของผู้ใช้
        /// </summary>
        public static bool ShowsEditTools(bool embeddedInHost) => !embeddedInHost;
    }
}
